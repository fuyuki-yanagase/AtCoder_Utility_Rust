use rustc_lexer::TokenKind;
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

const GENERATED: &str = "// @generated by _rust_import. 直接編集せず生成コマンドを実行してください。";
const BORDER: &str = "// ======================================================================================";

#[derive(Debug)]
struct Library {
    title: String,
    dependencies: Vec<String>,
    body: String,
}

fn normalize(source: &str) -> String {
    source.replace("\r\n", "\n")
}

fn identifier(value: &str) -> bool {
    let mut chars = value.chars();
    chars.next().is_some_and(|c| c == '_' || c.is_ascii_alphabetic())
        && chars.all(|c| c == '_' || c.is_ascii_alphanumeric())
}

/// コメント内の疑似importを依存として扱わないよう、既存のRust lexerを使う。
fn tokens(source: &str) -> Vec<&str> {
    let mut offset = 0;
    let mut result = Vec::new();
    for token in rustc_lexer::tokenize(source) {
        let text = &source[offset..offset + token.len];
        offset += token.len;
        if !matches!(
            token.kind,
            TokenKind::Whitespace | TokenKind::LineComment | TokenKind::BlockComment { .. }
        ) {
            result.push(text);
        }
    }
    result
}

fn selected_names(words: &[&str]) -> bool {
    if words == ["*"] || (words.len() == 1 && identifier(words[0])) {
        return true;
    }
    if words.first() != Some(&"{") || words.last() != Some(&"}") {
        return false;
    }
    let mut expect_name = true;
    let mut count = 0;
    for word in &words[1..words.len() - 1] {
        if expect_name {
            if !identifier(word) || *word == "as" {
                return false;
            }
            count += 1;
        } else if *word != "," {
            return false;
        }
        expect_name = !expect_name;
    }
    count > 0
}

/// 対応していない構文を黙って捨てると、コピペ先でだけ壊れるためエラーにする。
fn dependencies(prelude: &str) -> Result<Vec<String>, String> {
    let words = tokens(prelude);
    let mut result = Vec::new();
    let mut index = 0;
    while index < words.len() {
        if words[index] == "pub" {
            index += 1;
        }
        let statement = &words[index..];
        if statement.len() < 8
            || statement[..4] != ["use", "crate", ":", ":"]
            || !identifier(statement[4])
            || statement[5..7] != [":", ":"]
        {
            return Err("依存importを確認してください。use crate::<module>::*; などの形式に対応しています。".into());
        }
        let end = statement.iter().position(|word| *word == ";").ok_or("依存importの末尾にセミコロンがありません。")?;
        if !selected_names(&statement[7..end]) {
            return Err(
                "依存importの別名・入れ子の指定には対応していません。単一名・名前の一覧・* を指定してください。".into(),
            );
        }
        let module = statement[4].to_owned();
        if !result.contains(&module) {
            result.push(module);
        }
        index += end + 1;
    }
    Ok(result)
}

/// 本文内の参照を黙って残さない。入れ子のmod内で完結するsuper::は維持する。
fn validate_body(body: &str) -> Result<(), String> {
    let words = tokens(body);
    let mut scopes = Vec::new();
    let mut module_depth = 0;
    for (index, word) in words.iter().enumerate() {
        match *word {
            "{" => {
                let module = index >= 2 && words[index - 2] == "mod" && identifier(words[index - 1]);
                scopes.push(module);
                module_depth += usize::from(module);
            }
            "}" => {
                if scopes.pop() == Some(true) {
                    module_depth -= 1;
                }
            }
            "crate" | "super" if words.get(index + 1..index + 3) == Some(&[":", ":"][..]) => {
                if *word == "crate" {
                    return Err(
                        "本文のcrate::参照には対応していません。依存は共通ヘッダー直後のuse crateで指定してください。"
                            .into(),
                    );
                }
                let mut hops = 1;
                let mut next = index + 3;
                while words.get(next) == Some(&"super") {
                    hops += 1;
                    if words.get(next + 1..next + 3) != Some(&[":", ":"][..]) {
                        break;
                    }
                    next += 3;
                }
                if hops > module_depth {
                    return Err(
                        "本文のsuper::参照がコピペ対象の外を指しています。依存はuse crateで指定してください。".into(),
                    );
                }
            }
            _ => {}
        }
    }
    Ok(())
}

fn parse_library(source: &str, common: &str) -> Result<Library, String> {
    let source = normalize(source);
    let (title, rest) = source.split_once('\n').ok_or("掲載名の先頭コメントがありません。")?;
    if !title.starts_with("// ") {
        return Err("1行目を掲載名のコメントにしてください。".into());
    }
    let expected = format!("{}\n", common.trim_end());
    let rest = rest
        .strip_prefix(&expected)
        .ok_or("共通ヘッダーがcommon_header.rsと一致しません。先に原本のヘッダーを揃えてください。")?;
    let start = rest.find(BORDER).ok_or("ライブラリ本文の区切り線がありません。")?;
    let body = &rest[start..];
    if !body.starts_with(&format!("{BORDER}\n").repeat(4)) {
        return Err("ライブラリ本文の先頭には区切り線を4本並べてください。".into());
    }
    validate_body(body)?;
    Ok(Library {
        title: title.to_owned(),
        dependencies: dependencies(&rest[..start])?,
        body: body.trim_end_matches('\n').to_owned(),
    })
}

/// 後順巡回で依存を先に置き、ダイヤモンド型の共有依存も1回だけ出力する。
fn visit(
    name: &str,
    libraries: &BTreeMap<String, Library>,
    visiting: &mut Vec<String>,
    emitted: &mut BTreeSet<String>,
    order: &mut Vec<String>,
) -> Result<(), String> {
    if emitted.contains(name) {
        return Ok(());
    }
    if visiting.iter().any(|current| current == name) {
        visiting.push(name.to_owned());
        return Err(format!("循環依存があります: {}", visiting.join(" → ")));
    }
    let library = libraries.get(name).ok_or_else(|| format!("依存先の原本がありません: src/{name}.rs"))?;
    visiting.push(name.to_owned());
    for dependency in &library.dependencies {
        visit(dependency, libraries, visiting, emitted, order)?;
    }
    visiting.pop();
    emitted.insert(name.to_owned());
    order.push(name.to_owned());
    Ok(())
}

fn render(common: &str, libraries: &BTreeMap<String, Library>) -> Result<BTreeMap<PathBuf, String>, String> {
    let mut outputs = BTreeMap::new();
    let mut registry =
        format!("{GENERATED}\n// 各ファイルを独立したモジュールとしてCargo・rust-analyzerに登録する。\n\n");
    for (name, library) in libraries {
        let mut order = Vec::new();
        visit(name, libraries, &mut Vec::new(), &mut BTreeSet::new(), &mut order)?;
        let mut source = format!("{}\n{GENERATED}\n{}\n\n", library.title, common.trim_end());
        for dependency in order {
            source.push_str(&libraries[&dependency].body);
            source.push_str("\n\n");
        }
        source.pop();
        outputs.insert(PathBuf::from(format!("src/import/{name}_import.rs")), source);
        registry.push_str(&format!("#[path = \"../src/import/{name}_import.rs\"]\nmod {name}_import;\n\n"));
    }
    registry.push_str("#[path = \"support/import_usage.rs\"]\nmod usage;\n");
    outputs.insert(PathBuf::from("tests/imports.rs"), registry);
    Ok(outputs)
}

fn read(path: &Path) -> Result<String, String> {
    fs::read_to_string(path).map_err(|_| format!("ファイルを読み込めません: {}", path.display()))
}

fn load(root: &Path) -> Result<(String, BTreeMap<String, Library>), String> {
    let common = normalize(&read(&root.join("common_header.rs"))?);
    let mut libraries = BTreeMap::new();
    for entry in fs::read_dir(root.join("src")).map_err(|_| "srcフォルダーを読み込めません。")? {
        let entry = entry.map_err(|_| "srcフォルダーの一覧を読み込めません。")?;
        if !entry.file_type().map_err(|_| "原本の種類を確認できません。")?.is_file() {
            continue;
        }
        let path = entry.path();
        if path.extension().and_then(|value| value.to_str()) != Some("rs") {
            continue;
        }
        let name = path.file_stem().and_then(|value| value.to_str()).ok_or("原本のファイル名を確認してください。")?;
        if matches!(name, "lib" | "main") {
            continue;
        }
        if !identifier(name) {
            return Err(format!("原本のファイル名には英数字とアンダースコアを使用してください: {name}"));
        }
        let library = parse_library(&read(&path)?, &common).map_err(|error| format!("src/{name}.rs: {error}"))?;
        libraries.insert(name.to_owned(), library);
    }
    if libraries.is_empty() {
        return Err("src直下に対象のライブラリがありません。".into());
    }
    Ok((common, libraries))
}

fn owned(source: &str) -> bool {
    source.lines().take(2).any(|line| line == GENERATED)
}

/// 出力先のリンクが別の場所を指している場合は、書き込み・削除を行わない。
fn verify_destination(root: &Path, destination: &Path) -> Result<(), String> {
    let root = root.canonicalize().map_err(|_| "プロジェクトの場所を確認できません。")?;
    let mut ancestor = destination.parent().ok_or("生成先を確認できません。")?;
    while !ancestor.exists() {
        ancestor = ancestor.parent().ok_or("生成先を確認できません。")?;
    }
    let parent = ancestor.canonicalize().map_err(|_| "生成先の場所を確認できません。")?;
    if !parent.starts_with(&root) || fs::symlink_metadata(destination).is_ok_and(|meta| meta.file_type().is_symlink()) {
        return Err(format!("プロジェクト外やリンク先には生成できません: {}", destination.display()));
    }
    Ok(())
}

/// 全入力と既存出力を検証してから書く。--checkではフォルダーも作成しない。
fn synchronize(root: &Path, outputs: &BTreeMap<PathBuf, String>, check: bool) -> Result<(), String> {
    let mut updates = Vec::new();
    let mut stale = Vec::new();
    for (relative, expected) in outputs {
        let path = root.join(relative);
        verify_destination(root, &path)?;
        match fs::read_to_string(&path) {
            Ok(current) => {
                if !owned(&current) {
                    return Err(format!("手書きのファイルは上書きしません: {}", relative.display()));
                }
                if current != *expected {
                    updates.push(relative.clone());
                }
            }
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => updates.push(relative.clone()),
            Err(_) => return Err(format!("既存の生成ファイルを確認できません: {}", relative.display())),
        }
    }
    let directory = root.join("src/import");
    if directory.exists() {
        for entry in fs::read_dir(&directory).map_err(|_| "src/importを確認できません。")? {
            let path = entry.map_err(|_| "src/importの一覧を確認できません。")?.path();
            let Some(filename) = path.file_name().and_then(|value| value.to_str()) else { continue };
            if !filename.ends_with("_import.rs") {
                continue;
            }
            let relative = PathBuf::from("src/import").join(filename);
            if !outputs.contains_key(&relative) {
                verify_destination(root, &path)?;
                if !owned(&read(&path)?) {
                    return Err(format!("手書きのファイルは削除しません: {}", relative.display()));
                }
                stale.push(relative);
            }
        }
    }
    stale.sort();
    if check {
        updates.extend(stale);
        if !updates.is_empty() {
            return Err(format!(
                "コピペ用ファイルの再生成が必要です:\n{}",
                updates.iter().map(|path| path.display().to_string()).collect::<Vec<_>>().join("\n")
            ));
        }
        return Ok(());
    }
    for relative in updates {
        let path = root.join(&relative);
        fs::create_dir_all(path.parent().unwrap()).map_err(|_| "生成先フォルダーを作成できません。")?;
        fs::write(&path, &outputs[&relative])
            .map_err(|_| format!("生成ファイルを書き込めません: {}", relative.display()))?;
    }
    for relative in stale {
        fs::remove_file(root.join(&relative))
            .map_err(|_| format!("古い生成ファイルを削除できません: {}", relative.display()))?;
    }
    Ok(())
}

fn run() -> Result<(), String> {
    let args: Vec<_> = std::env::args().skip(1).collect();
    let check = match args.as_slice() {
        [] => false,
        [arg] if arg == "--check" => true,
        _ => return Err("使い方: cargo run --bin _rust_import --locked -- [--check]".into()),
    };
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let (common, libraries) = load(root)?;
    let outputs = render(&common, &libraries)?;
    synchronize(root, &outputs, check)?;
    println!(
        "{}件のコピペ用ファイルを{}。",
        libraries.len(),
        if check { "検証しました" } else { "生成しました" }
    );
    Ok(())
}

fn main() {
    if let Err(error) = run() {
        eprintln!("生成できませんでした。{error}");
        std::process::exit(1);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::atomic::{AtomicUsize, Ordering};

    const COMMON: &str = "#![allow(unused)]\nconst LIMIT: usize = 10;\n";

    fn source(imports: &str, body: &str) -> String {
        format!("// サンプル\n{COMMON}\n{imports}\n{}{body}\n", format!("{BORDER}\n").repeat(4))
    }

    fn library(imports: &str, body: &str) -> Library {
        parse_library(&source(imports, body), COMMON).unwrap()
    }

    #[test]
    fn expands_transitive_and_shared_dependencies_once_in_order() {
        let libraries = BTreeMap::from([
            ("a".into(), library("use crate::b::*;\nuse crate::c::*;", "fn a() {}")),
            ("b".into(), library("pub use crate::d::{D, E,};", "fn b() {}")),
            ("c".into(), library("use crate::d::D;", "fn c() {}")),
            ("d".into(), library("", "struct D; struct E;")),
        ]);
        let rendered = render(COMMON, &libraries).unwrap();
        let a = &rendered[Path::new("src/import/a_import.rs")];
        assert_eq!(a.matches("const LIMIT").count(), 1);
        assert_eq!(a.matches("struct D;").count(), 1);
        assert!(!a.contains("use crate::"));
        assert!(a.find("struct D;") < a.find("fn b()"));
        assert!(a.find("fn b()") < a.find("fn c()"));
        assert!(a.find("fn c()") < a.find("fn a()"));
    }

    #[test]
    fn rejects_cycles_and_missing_dependencies() {
        let mut libraries = BTreeMap::from([
            ("a".into(), library("use crate::b::*;", "fn a() {}")),
            ("b".into(), library("use crate::a::*;", "fn b() {}")),
        ]);
        assert!(render(COMMON, &libraries).unwrap_err().contains("循環依存"));
        libraries.remove("b");
        assert!(render(COMMON, &libraries).unwrap_err().contains("src/b.rs"));
    }

    #[test]
    fn preserves_bodies_urls_and_ignores_pseudo_imports() {
        let body = "// Library URL : https://example.com/pinned\nconst TEXT: &str = r#\"use crate::missing::*;\"#;\n// use crate::missing::*;";
        let original = source("/* use crate::missing::*; */\n// use crate::missing::*;", body);
        let parsed = parse_library(&original.replace("\n", "\r\n"), COMMON).unwrap();
        assert!(parsed.dependencies.is_empty());
        let rendered = render(COMMON, &BTreeMap::from([("a".into(), parsed)])).unwrap();
        let a = &rendered[Path::new("src/import/a_import.rs")];
        assert!(a.ends_with(&format!("{body}\n")));
        assert!(!a.contains('\r'));
    }

    #[test]
    fn rejects_header_drift_and_unsupported_imports() {
        assert!(parse_library(&source("", "fn a() {}").replace("LIMIT", "OTHER"), COMMON).is_err());
        for imports in [
            "use crate::a::A as Alias;",
            "pub use crate::a::{A as Alias};",
            "use crate::{a, b};",
            "fn lost() {}",
            "use crate::a::*",
        ] {
            assert!(parse_library(&source(imports, "fn a() {}"), COMMON).is_err(), "{imports}");
        }
    }

    #[test]
    fn rejects_external_body_paths_but_keeps_nested_module_references() {
        for body in [
            "use crate::missing::*;",
            "fn a() { crate::missing::call(); }",
            "fn a() { super::outside(); }",
            "mod nested { fn a() { super::super::outside(); } }",
        ] {
            assert!(parse_library(&source("", body), COMMON).is_err(), "{body}");
        }
        let body = "fn root() {} mod a { mod b { fn call() { super::super::root(); } } }";
        assert!(parse_library(&source("", body), COMMON).is_ok());
    }

    struct Fixture(PathBuf);

    impl Fixture {
        fn new() -> Self {
            static NEXT: AtomicUsize = AtomicUsize::new(0);
            let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("target").join(format!(
                "rust-import-test-{}-{}",
                std::process::id(),
                NEXT.fetch_add(1, Ordering::Relaxed)
            ));
            fs::create_dir_all(&root).unwrap();
            Self(root)
        }
    }

    impl Drop for Fixture {
        fn drop(&mut self) {
            let target = Path::new(env!("CARGO_MANIFEST_DIR")).join("target");
            if self.0.starts_with(target) {
                let _ = fs::remove_dir_all(&self.0);
            }
        }
    }

    #[test]
    fn checks_without_writing_and_refuses_handwritten_files_before_updates() {
        let fixture = Fixture::new();
        let outputs = render(COMMON, &BTreeMap::from([("a".into(), library("", "fn a() {}"))])).unwrap();
        assert!(synchronize(&fixture.0, &outputs, true).is_err());
        assert!(!fixture.0.join("src").exists());
        synchronize(&fixture.0, &outputs, false).unwrap();
        synchronize(&fixture.0, &outputs, true).unwrap();
        let path = fixture.0.join("src/import/a_import.rs");
        fs::write(&path, "// 手書き\n").unwrap();
        fs::remove_file(fixture.0.join("tests/imports.rs")).unwrap();
        assert!(synchronize(&fixture.0, &outputs, false).unwrap_err().contains("手書き"));
        assert_eq!(read(&path).unwrap(), "// 手書き\n");
        assert!(!fixture.0.join("tests/imports.rs").exists());
    }

    #[test]
    fn removes_only_owned_stale_outputs_and_detects_drift() {
        let fixture = Fixture::new();
        let mut outputs = render(COMMON, &BTreeMap::from([("a".into(), library("", "fn a() {}"))])).unwrap();
        synchronize(&fixture.0, &outputs, false).unwrap();
        let stale = fixture.0.join("src/import/old_import.rs");
        fs::write(&stale, format!("{GENERATED}\n")).unwrap();
        assert!(synchronize(&fixture.0, &outputs, true).is_err());
        assert_eq!(read(&stale).unwrap(), format!("{GENERATED}\n"));
        synchronize(&fixture.0, &outputs, false).unwrap();
        assert!(!stale.exists());
        let original = read(&fixture.0.join("src/import/a_import.rs")).unwrap();
        outputs.get_mut(Path::new("src/import/a_import.rs")).unwrap().push_str("// 更新\n");
        assert!(synchronize(&fixture.0, &outputs, true).is_err());
        assert_eq!(read(&fixture.0.join("src/import/a_import.rs")).unwrap(), original);
        synchronize(&fixture.0, &outputs, false).unwrap();
        synchronize(&fixture.0, &outputs, true).unwrap();
        fs::write(&stale, "// 手書き\n").unwrap();
        assert!(synchronize(&fixture.0, &outputs, false).is_err());
        assert!(stale.exists());
    }
}
